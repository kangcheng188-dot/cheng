  /* ---------------- 随机对战 ---------------- */

  var SK_DIFF = { e: AI.dozy, n: AI.calm, h: AI.sharp, x: AI.cruel };

  function makeSkirmish(opt) {
    var enemies = Math.max(1, Math.min(4, opt.enemies | 0 || 2));
    var sizeKey = opt.size || 'm';
    var count = { s: 9, m: 14, l: 20 }[sizeKey] || 14;
    var diff = SK_DIFF[opt.diff] || AI.calm;

    var W = global.TW.WORLD_W, H = global.TW.WORLD_H;
    var pad = 100, minGap = 128;
    var pts = [], tries = 0;
    while (pts.length < count && tries++ < 4000) {
      var p = { x: pad + Math.random() * (W - pad * 2), y: pad + Math.random() * (H - pad * 2) };
      var ok = true;
      for (var i = 0; i < pts.length; i++) {
        if (global.TW.dist(p.x, p.y, pts[i].x, pts[i].y) < minGap) { ok = false; break; }
      }
      if (ok) pts.push(p);
    }

    // 玩家占最左边的点，敌人依次占离玩家最远、且彼此最远的点
    pts.sort(function (a, b) { return a.x - b.x; });
    var cells = [], used = {};
    var base = pts[0];
    cells.push(C(base.x, base.y, 1, 40, 120));
    used[0] = 1;

    var order = [2, 3, 4, 5];
    for (var e = 0; e < enemies; e++) {
      var bestIdx = -1, bestScore = -1;
      for (var j = 0; j < pts.length; j++) {
        if (used[j]) continue;
        var score = 1e9;
        for (var k in used) score = Math.min(score, global.TW.dist(pts[j].x, pts[j].y, pts[k].x, pts[k].y));
        if (score > bestScore) { bestScore = score; bestIdx = j; }
      }
      if (bestIdx < 0) break;
      used[bestIdx] = 1;
      cells.push(C(pts[bestIdx].x, pts[bestIdx].y, order[e], 40, 120));
    }

    for (var m = 0; m < pts.length; m++) {
      if (used[m]) continue;
      var big = Math.random() < 0.22;
      cells.push(C(pts[m].x, pts[m].y, 0,
        big ? 26 + Math.floor(Math.random() * 22) : 10 + Math.floor(Math.random() * 14),
        big ? 150 : 100));
    }

    var ai = {};
    for (var q = 0; q < enemies; q++) ai[order[q]] = diff;

    return {
      no: 0, name: '随机对战', par: 60 + count * 9, custom: true,
      hint: null, winAll: false, cells: cells, ai: ai
    };
  }

